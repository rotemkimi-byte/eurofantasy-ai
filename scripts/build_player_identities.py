"""Build deterministic E2026 identities from official IDs; review aliases explicitly."""
import json,re,unicodedata
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def normalize(value):
    text=''.join(c for c in unicodedata.normalize('NFD',str(value or '')) if not unicodedata.combining(c)).lower()
    return ' '.join(sorted(re.sub('[^a-z0-9]+',' ',text.replace("'",'').replace('’','')).split()))
# Verified against E2026 official person codes and clubs. No approximate matching.
VERIFIED={3771:'009863',4096:'012606',7197:'014127',11517:'015162',11494:'014728',11512:'014734',4758:'012742',3980:'007553',11538:'014739',11535:'015102',7867:'014015'}
def build(root=ROOT):
    people={};conflicts=[]
    for path in sorted((root/'data/backtest/cache').glob('E2026-*-stats.json'),key=lambda p:int(p.name.split('-')[1])):
        code=int(path.name.split('-')[1]);box=json.loads(path.read_text())
        for side in ['local','road']:
            for row in (box.get(side) or {}).get('players',[]):
                player=row.get('player') or {};person=player.get('person') or {};pid=str(person.get('code') or '').removeprefix('P')
                if not pid or not person.get('name'):continue
                club=(player.get('club') or {}).get('name');r=people.setdefault(pid,{'euroleagueId':pid,'fantasyId':None,'officialName':person['name'],'displayName':person['name'],'aliases':[],'currentTeam':club,'teamHistory':[]})
                if person['name'] not in r['aliases']:r['aliases'].append(person['name'])
                r['officialName']=person['name'];r['currentTeam']=club
                r['teamHistory'].append({'gameCode':code,'team':club})
    index={}
    for r in people.values():
        for name in r['aliases']:index.setdefault(normalize(name),set()).add(r['euroleagueId'])
    market=json.loads((root/'data/players.json').read_text());unresolved=[]
    previous=root/'data/player-identities.json'
    old={r['fantasyId']:r for r in json.loads(previous.read_text()).get('players',[]) if r.get('fantasyId')} if previous.exists() else {}
    for p in market:
        if p.get('pos') not in ['G','F','C']:continue
        fid=p.get('fantasy_id');ids=index.get(normalize(p['name']),set());explicit=VERIFIED.get(fid) or old.get(fid,{}).get('euroleagueId')
        if explicit:
            ids={explicit} if explicit in people else set()
        if len(ids)!=1:
            unresolved.append({'fantasyId':fid,'name':p['name'],'team':p['team'],'reason':'ambiguous' if len(ids)>1 else 'no-official-record','candidates':sorted(ids)})
            people['fantasy:'+str(fid)]={'euroleagueId':None,'fantasyId':fid,'officialName':None,'displayName':p['name'],'aliases':[p['name']],'currentTeam':p['team'],'teamHistory':[]}
            continue
        r=people[next(iter(ids))]
        if r['fantasyId'] not in [None,fid]:conflicts.append({'official':r['euroleagueId'],'fantasy':[r['fantasyId'],fid]});continue
        r.update(fantasyId=fid,displayName=p['name'],currentTeam=p['team'])
        if p['name'] not in r['aliases']:r['aliases'].append(p['name'])
        for alias in old.get(fid,{}).get('aliases',[]):
            if alias not in r['aliases']:r['aliases'].append(alias)
    for r in people.values():r['key']= ' '.join(sorted(re.sub('[^a-z0-9]+',' ',''.join(c for c in unicodedata.normalize('NFD',r['officialName'] or r['displayName']) if not unicodedata.combining(c)).lower()).split()));r['aliases'].sort()
    result={'schema':'player-identities-v1','season':'E2026','players':sorted(people.values(),key=lambda r:(r['key'],str(r['fantasyId']))),'unresolved':unresolved,'conflicts':conflicts}
    if conflicts:raise ValueError('Conflicting IDs: '+str(conflicts))
    text=json.dumps(result,ensure_ascii=False,separators=(',',':'))
    (root/'data/player-identities.json').write_text(text+'\n')
    (root/'player-identities.js').write_text('/* Generated by scripts/build_player_identities.py */\nglobalThis.PlayerIdentityRegistry='+text+';\n')
    print(json.dumps({'marketPlayers':sum(p['pos'] in ['G','F','C'] for p in market),'linked':sum(r['fantasyId'] is not None and r['euroleagueId'] is not None for r in people.values()),'unresolved':len(unresolved)}))
    return result
if __name__=='__main__':build()
