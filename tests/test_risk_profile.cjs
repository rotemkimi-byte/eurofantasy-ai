'use strict';
const assert = require('node:assert/strict');
const R = require('../risk-profile-core.js');
const official = require('../data/official-offense.json');
const events = require('../data/advanced-players.json');
const real = Object.values(official.players).find(p => p.games.filter(g => g.minutes>0).length>=6);
const newest = real.games.reduce((a,b)=>Date.parse(a.date)>Date.parse(b.date)?a:b);
const position = {Guard:'G',Forward:'F',Center:'C'}[newest.positionName];
const player = {name:real.name,team:newest.team,pos:position,status:'active'};
const now = Date.parse(official.updated_at);
const fixture = {opponent:newest.opponent,home:true,start:now+86400000};
const forecast = {expected:12,minutes:22};
const prepared = R.prepare(official,events,now);
const profile = R.describe(prepared,player,fixture,forecast);
assert.ok(profile.games>=3);
assert.ok(profile.rows.pirVar.count>=3);
assert.ok(profile.rows.daysOff.value>0);
assert.ok(R.metrics.length>=80);
assert.ok(!R.prepare({...official,season:'E2025'},events,now).context.games.size);
assert.ok(!R.prepare({...official,updated_at:new Date(now+1).toISOString()},events,now,{pregame:true}).context.games.size);
assert.ok(!R.prepare(official,events,now,{pregame:true,fixtureCode:newest.gameCode}).context.games.has(String(newest.gameCode)));
assert.equal(R.outcome.low(10),true);
assert.equal(R.outcome.miss5(7,12),true);
assert.equal(R.outcome.miss5(7,11.99),false);
assert.equal(R.outcome.miss10(2,12),true);
assert.equal(R.outcome.miss10(3,12),false);
assert.deepEqual(R.evaluate(profile,forecast,player,null).risks,{low:null,miss5:null,miss10:null});
const sample = Array.from({length:320},(_,i)=>({
 expected:12,actual:i<160?13:1,values:{pirVar:i/20,ftPoints:i%28,minVar:i%7}
}));
const models = Object.fromEntries(R.endpoints.map(id=>[id,R.fit(sample,id)]));
const validation = Object.fromEntries(R.endpoints.map(id=>[id,{calibrated:false,directional:true}]));
const runtime = {season:R.season,version:R.version,models,validation};
const high = {...profile,values:{pirVar:16,ftPoints:24,minVar:5}};
const result = R.evaluate(high,forecast,player,runtime);
assert.equal(result.risks.miss5.level,3);
assert.equal(result.risks.miss5.probability,null);
assert.equal(new Set(result.factors.map(f=>f.group)).size,result.factors.length);
assert.equal(R.evaluate(high,forecast,{...player,status:'out'},runtime).risks.miss5,null);
assert.equal(R.evaluate({...high,games:2},forecast,player,runtime).risks.miss5,null);
runtime.validation.miss5.calibrated=true;
assert.ok(R.evaluate({...high,games:6},forecast,player,runtime).risks.miss5.probability>0.9);
assert.equal(R.evaluate({...high,games:5},forecast,player,runtime).risks.miss5.probability,null);
console.log('Risk profile season, pregame boundaries, scoring, feature families and calibration guards passed.');
